-- =============================================================================
-- Kadai — 0007 purchases: purchase orders, purchase bills (GRN + supplier
-- invoice), debit notes (purchase returns). Purchase prices are per PACK, excl. tax.
-- =============================================================================

CREATE TABLE purchase_orders (
  id                uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  tenant_id         uuid NOT NULL REFERENCES tenants(id) ON DELETE CASCADE,
  store_id          uuid NOT NULL,
  supplier_id       uuid NOT NULL,
  number            text NOT NULL,
  fy                text NOT NULL,
  order_date        date NOT NULL,
  expected_date     date,
  status            text NOT NULL DEFAULT 'draft' CHECK (status IN ('draft', 'sent', 'partially_received', 'received', 'closed', 'cancelled')),
  is_interstate     boolean NOT NULL DEFAULT false,
  taxable_paise     bigint NOT NULL DEFAULT 0,
  tax_paise         bigint NOT NULL DEFAULT 0,
  total_paise       bigint NOT NULL DEFAULT 0,
  notes             text,
  terms             text,
  sent_at           timestamptz,
  created_by        uuid REFERENCES users(id),
  created_at        timestamptz NOT NULL DEFAULT now(),
  updated_at        timestamptz NOT NULL DEFAULT now(),
  UNIQUE (tenant_id, id),
  UNIQUE (tenant_id, fy, number),
  FOREIGN KEY (tenant_id, store_id) REFERENCES stores (tenant_id, id),
  FOREIGN KEY (tenant_id, supplier_id) REFERENCES suppliers (tenant_id, id)
);

CREATE TABLE purchase_order_lines (
  id                  uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  tenant_id           uuid NOT NULL REFERENCES tenants(id) ON DELETE CASCADE,
  purchase_order_id   uuid NOT NULL,
  line_no             integer NOT NULL,
  product_id          uuid NOT NULL,
  qty_milli           bigint NOT NULL CHECK (qty_milli > 0),
  received_qty_milli  bigint NOT NULL DEFAULT 0 CHECK (received_qty_milli >= 0),
  unit_cost_paise     bigint NOT NULL DEFAULT 0,
  gst_rate_bp         integer NOT NULL DEFAULT 0,
  taxable_paise       bigint NOT NULL DEFAULT 0,
  tax_paise           bigint NOT NULL DEFAULT 0,
  total_paise         bigint NOT NULL DEFAULT 0,
  notes               text,
  UNIQUE (tenant_id, id),
  UNIQUE (purchase_order_id, line_no),
  FOREIGN KEY (tenant_id, purchase_order_id) REFERENCES purchase_orders (tenant_id, id) ON DELETE CASCADE,
  FOREIGN KEY (tenant_id, product_id) REFERENCES products (tenant_id, id)
);

CREATE TABLE purchase_bills (
  id                      uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  tenant_id               uuid NOT NULL REFERENCES tenants(id) ON DELETE CASCADE,
  store_id                uuid NOT NULL,
  supplier_id             uuid NOT NULL,
  purchase_order_id       uuid,
  number                  text,                 -- internal GRN number, assigned on posting
  fy                      text,
  supplier_invoice_no     text NOT NULL,
  supplier_invoice_date   date NOT NULL,
  received_date           date NOT NULL,
  due_date                date,
  supplier_gstin          text,
  supplier_state_code     text,
  is_interstate           boolean NOT NULL DEFAULT false,
  reverse_charge          boolean NOT NULL DEFAULT false,
  itc_eligible            boolean NOT NULL DEFAULT true,
  status                  text NOT NULL DEFAULT 'draft' CHECK (status IN ('draft', 'posted', 'cancelled')),
  gross_paise             bigint NOT NULL DEFAULT 0,
  discount_paise          bigint NOT NULL DEFAULT 0,
  taxable_paise           bigint NOT NULL DEFAULT 0,
  cgst_paise              bigint NOT NULL DEFAULT 0,
  sgst_paise              bigint NOT NULL DEFAULT 0,
  igst_paise              bigint NOT NULL DEFAULT 0,
  cess_paise              bigint NOT NULL DEFAULT 0,
  other_charges_paise     bigint NOT NULL DEFAULT 0,   -- freight etc. (capitalised into inventory cost)
  round_off_paise         bigint NOT NULL DEFAULT 0 CHECK (round_off_paise BETWEEN -99 AND 99),
  total_paise             bigint NOT NULL DEFAULT 0 CHECK (total_paise >= 0),
  paid_paise              bigint NOT NULL DEFAULT 0,
  returned_paise          bigint NOT NULL DEFAULT 0,
  due_paise               bigint NOT NULL DEFAULT 0,
  payment_status          text NOT NULL DEFAULT 'unpaid' CHECK (payment_status IN ('unpaid', 'partial', 'paid')),
  notes                   text,
  attachment_file_id      uuid,
  posted_at               timestamptz,
  posted_by               uuid REFERENCES users(id),
  cancelled_at            timestamptz,
  cancelled_by            uuid REFERENCES users(id),
  cancel_reason           text,
  created_by              uuid REFERENCES users(id),
  created_at              timestamptz NOT NULL DEFAULT now(),
  updated_at              timestamptz NOT NULL DEFAULT now(),
  UNIQUE (tenant_id, id),
  UNIQUE (tenant_id, fy, number),
  FOREIGN KEY (tenant_id, store_id) REFERENCES stores (tenant_id, id),
  FOREIGN KEY (tenant_id, supplier_id) REFERENCES suppliers (tenant_id, id),
  FOREIGN KEY (tenant_id, purchase_order_id) REFERENCES purchase_orders (tenant_id, id),
  FOREIGN KEY (tenant_id, attachment_file_id) REFERENCES files (tenant_id, id),
  CHECK (total_paise = taxable_paise + cgst_paise + sgst_paise + igst_paise + cess_paise + other_charges_paise + round_off_paise),
  CHECK (NOT is_interstate OR (cgst_paise = 0 AND sgst_paise = 0)),
  CHECK (is_interstate OR igst_paise = 0)
);
-- A supplier invoice number can be entered only once per supplier per FY (duplicate-entry guard)
CREATE UNIQUE INDEX purchase_bills_supplier_invoice_uq
  ON purchase_bills (tenant_id, supplier_id, lower(supplier_invoice_no), fy)
  WHERE status <> 'cancelled' AND fy IS NOT NULL;
CREATE INDEX purchase_bills_date_idx ON purchase_bills (tenant_id, received_date DESC);
CREATE INDEX purchase_bills_due_idx ON purchase_bills (tenant_id, supplier_id) WHERE due_paise > 0 AND status = 'posted';

CREATE TABLE purchase_bill_lines (
  id                    uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  tenant_id             uuid NOT NULL REFERENCES tenants(id) ON DELETE CASCADE,
  bill_id               uuid NOT NULL,
  line_no               integer NOT NULL,
  product_id            uuid NOT NULL,
  purchase_order_line_id uuid,
  batch_id              uuid,                 -- created/resolved on posting from batch_no
  batch_no              text,
  mfg_date              date,
  expiry_date           date,
  hsn_code              text,
  unit                  text NOT NULL,
  pack_size             integer NOT NULL DEFAULT 1 CHECK (pack_size >= 1),
  qty_milli             bigint NOT NULL CHECK (qty_milli > 0),
  free_qty_milli        bigint NOT NULL DEFAULT 0 CHECK (free_qty_milli >= 0),
  mrp_paise             bigint,
  unit_cost_paise       bigint NOT NULL CHECK (unit_cost_paise >= 0),   -- per pack excl. tax, before discount
  discount_bp           integer NOT NULL DEFAULT 0 CHECK (discount_bp BETWEEN 0 AND 10000),
  discount_paise        bigint NOT NULL DEFAULT 0,
  gross_paise           bigint NOT NULL,
  taxable_paise         bigint NOT NULL,
  gst_rate_bp           integer NOT NULL DEFAULT 0,
  cgst_paise            bigint NOT NULL DEFAULT 0,
  sgst_paise            bigint NOT NULL DEFAULT 0,
  igst_paise            bigint NOT NULL DEFAULT 0,
  cess_rate_bp          integer NOT NULL DEFAULT 0,
  cess_paise            bigint NOT NULL DEFAULT 0,
  total_paise           bigint NOT NULL,
  landed_unit_cost_paise bigint NOT NULL DEFAULT 0,   -- per pack incl. free qty & other charges allocation
  sale_price_paise      bigint,                -- optional new selling price to apply
  returned_qty_milli    bigint NOT NULL DEFAULT 0,
  UNIQUE (tenant_id, id),
  UNIQUE (bill_id, line_no),
  FOREIGN KEY (tenant_id, bill_id) REFERENCES purchase_bills (tenant_id, id) ON DELETE CASCADE,
  FOREIGN KEY (tenant_id, product_id) REFERENCES products (tenant_id, id),
  FOREIGN KEY (tenant_id, purchase_order_line_id) REFERENCES purchase_order_lines (tenant_id, id),
  FOREIGN KEY (tenant_id, batch_id) REFERENCES batches (tenant_id, id),
  CHECK (total_paise = taxable_paise + cgst_paise + sgst_paise + igst_paise + cess_paise)
);
CREATE INDEX purchase_bill_lines_product_idx ON purchase_bill_lines (tenant_id, product_id);

CREATE TABLE debit_notes (
  id                    uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  tenant_id             uuid NOT NULL REFERENCES tenants(id) ON DELETE CASCADE,
  store_id              uuid NOT NULL,
  supplier_id           uuid NOT NULL,
  bill_id               uuid,
  number                text NOT NULL,
  fy                    text NOT NULL,
  note_date             date NOT NULL,
  reason                text NOT NULL CHECK (reason IN ('return', 'damaged', 'expired', 'short_supply', 'price_difference', 'other')),
  status                text NOT NULL DEFAULT 'completed' CHECK (status IN ('completed', 'cancelled')),
  is_interstate         boolean NOT NULL DEFAULT false,
  taxable_paise         bigint NOT NULL DEFAULT 0,
  cgst_paise            bigint NOT NULL DEFAULT 0,
  sgst_paise            bigint NOT NULL DEFAULT 0,
  igst_paise            bigint NOT NULL DEFAULT 0,
  cess_paise            bigint NOT NULL DEFAULT 0,
  round_off_paise       bigint NOT NULL DEFAULT 0,
  total_paise           bigint NOT NULL DEFAULT 0,
  settlement            text NOT NULL DEFAULT 'adjust_due' CHECK (settlement IN ('adjust_due', 'refund_cash', 'refund_bank')),
  notes                 text,
  cancelled_at          timestamptz,
  cancelled_by          uuid REFERENCES users(id),
  created_by            uuid REFERENCES users(id),
  created_at            timestamptz NOT NULL DEFAULT now(),
  updated_at            timestamptz NOT NULL DEFAULT now(),
  UNIQUE (tenant_id, id),
  UNIQUE (tenant_id, fy, number),
  FOREIGN KEY (tenant_id, store_id) REFERENCES stores (tenant_id, id),
  FOREIGN KEY (tenant_id, supplier_id) REFERENCES suppliers (tenant_id, id),
  FOREIGN KEY (tenant_id, bill_id) REFERENCES purchase_bills (tenant_id, id),
  CHECK (total_paise = taxable_paise + cgst_paise + sgst_paise + igst_paise + cess_paise + round_off_paise)
);

CREATE TABLE debit_note_lines (
  id               uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  tenant_id        uuid NOT NULL REFERENCES tenants(id) ON DELETE CASCADE,
  debit_note_id    uuid NOT NULL,
  line_no          integer NOT NULL,
  bill_line_id     uuid,
  product_id       uuid NOT NULL,
  batch_id         uuid,
  hsn_code         text,
  unit             text NOT NULL,
  pack_size        integer NOT NULL DEFAULT 1,
  qty_milli        bigint NOT NULL CHECK (qty_milli > 0),
  unit_cost_paise  bigint NOT NULL,
  taxable_paise    bigint NOT NULL,
  gst_rate_bp      integer NOT NULL DEFAULT 0,
  cgst_paise       bigint NOT NULL DEFAULT 0,
  sgst_paise       bigint NOT NULL DEFAULT 0,
  igst_paise       bigint NOT NULL DEFAULT 0,
  cess_rate_bp     integer NOT NULL DEFAULT 0,
  cess_paise       bigint NOT NULL DEFAULT 0,
  total_paise      bigint NOT NULL,
  UNIQUE (tenant_id, id),
  UNIQUE (debit_note_id, line_no),
  FOREIGN KEY (tenant_id, debit_note_id) REFERENCES debit_notes (tenant_id, id) ON DELETE CASCADE,
  FOREIGN KEY (tenant_id, bill_line_id) REFERENCES purchase_bill_lines (tenant_id, id),
  FOREIGN KEY (tenant_id, product_id) REFERENCES products (tenant_id, id),
  FOREIGN KEY (tenant_id, batch_id) REFERENCES batches (tenant_id, id),
  CHECK (total_paise = taxable_paise + cgst_paise + sgst_paise + igst_paise + cess_paise)
);
