/** A cart line as the controller builds it (snapshot of the product). */
export function lineOf(product: PosProduct, over: Partial<CartLine> = {}): CartLine {
  return {
    key: `line-${product.id.slice(-4)}`,
    product,
    qty_milli: defaultQtyMilli(product),
    batch: null,
    batch_auto: true,
    store_price: null,
    tax_slabs: null,
    price_override_paise: null,
    discount_bp: 0,
    discount_paise: 0,
    serial_numbers: [],
    scanned_code: null,
    note: null,
    ...over,
  }
}

/** A line to dispatch with `add` (the reducer assigns the key). */
export function newLineOf(product: PosProduct, over: Partial<CartLine> = {}): NewCartLine {
  const { key: _key, ...rest } = lineOf(product, over)
  return rest
}

export function cartOf(lines: CartLine[], over: Partial<CartState> = {}): CartState {
  return { ...emptyCart(), lines, selected_key: lines.at(-1)?.key ?? null, ...over }
}

/** The quote the server answers for a cart priced locally (same engine → same numbers). */
